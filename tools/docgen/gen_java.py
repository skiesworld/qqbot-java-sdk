class Operation(object):

    def __init__(self, key, endpoint, entry, group_class):
        self.key = key
        self.endpoint = endpoint
        self.entry = entry
        self.title = entry.get('title') or endpoint.get('title') or ''
        self.doc = entry['doc']
        self.name = entry['method']
        self.group = entry['group']
        self.group_class = group_class
        self.const = const_name(entry['method'])
        self.http_method = endpoint['method']
        self.path = endpoint['path']
        self.path_names = path_params(endpoint)
        self.request_fields = request_fields_of(endpoint, entry)
        self.response_fields = response_fields_of(endpoint, entry)
        self.args = []              # [(java type, java name)] in signature order
        self.queries = []           # [(wire name, java name)] flattened into query parameters
        self.body_var = None        # java expression handed to execute() as the body
        self.body_locals = []       # statements that build a flattened body
        self.returns = 'void'
        self.response_literal = 'Void.class'
        self.response_generic = 'Void'
        self.request_class = None
        self.response_class = None

    def signature_imports(self):
        out = {PARAMS, ENDPOINTS}
        for java_type, _name in self.args:
            out |= imports_for(java_type, REGISTRY)
        out |= imports_for(self.returns, REGISTRY)
        for klass in (self.request_class, self.response_class):
            if klass is not None and klass.pkg != API_PKG:
                out.add(klass.fqn)
        return out


class DtoIndex(object):
    """Generated DTOs, so two operations may share one when their documented shape matches."""

    def __init__(self, registry):
        self.registry = registry
        self.seen = {}

    def get(self, pkg, java, op, fields, doc):
        slot = (pkg, java)
        shape = signature_of(fields)
        existing = self.seen.get(slot)
        if existing is not None:
            if existing['shape'] and shape and existing['shape'] != shape:
                raise Error('%s.%s is built for %s from %s but %s documents %s'
                            % (pkg, java, existing['key'], [s[0] for s in existing['shape']],
                               op.key, [s[0] for s in shape]))
            if not existing['shape'] and shape:
                existing['shape'] = shape
                self.registry.classes[java].fields = fields
            return self.registry.classes[java]
        klass = self.registry.classes.get(java)
        if klass is not None and klass.pkg != pkg:
            raise Error('%s %s clashes with %s' % (op.key, java, klass.fqn))
        if klass is not None:
            current = signature_of(klass.fields)
            if shape and current and shape != current:
                raise Error('%s: model %s already exists with fields %s'
                            % (op.key, java, [s[0] for s in current]))
            if not current:
                raise Error('%s: model %s is empty and cannot be reused as a dto' % (op.key, java))
            self.seen[slot] = {'key': op.key, 'shape': current}
            return klass
        created = self.registry.add(Klass(java, pkg, op.key, doc))
        created.fields = fields
        created.generated = True
        if not fields:
            raise Error('%s: dto %s documents no field' % (op.key, java))
        self.seen[slot] = {'key': op.key, 'shape': shape}
        return created


def _group_by_path(endpoints):
    groups = collections.OrderedDict()
    for endpoint in endpoints:
        groups.setdefault('%s %s' % (endpoint['method'], endpoint['path']), []).append(endpoint)
    return groups


def build_operations(spec, naming, keep):
    entries = naming['endpoints']
    groups = naming['apiGroups']
    known = collections.OrderedDict()
    for base, recs in _group_by_path(keep).items():
        if len(recs) == 1:
            known[base] = recs[0]
            continue
        # one path can carry several operations (guild mute vs batch member mute); the naming key of
        # the later ones is suffixed with the request fields that make them distinct
        shapes = [set(f['name'] for f in (r.get('body') or [])) for r in recs]
        common = set.intersection(*shapes)
        for rec, shape in zip(recs, shapes):
            extra = sorted(shape - common)
            key = base if not extra else base + '#' + '_'.join(extra)
            if key in known:
                raise Error('%s is documented twice with an identical request shape' % key)
            known[key] = rec
    missing = sorted(set(known) - set(entries))
    stale = sorted(set(entries) - set(known))
    if missing:
        raise Error('\n'.join(['naming.json has no entry for %d operation(s):' % len(missing)]
                              + ['  %s' % key for key in missing]))
    if stale:
        raise Error('\n'.join(['naming.json names %d operation(s) spec.json does not have:' % len(stale)]
                              + ['  %s' % key for key in stale]))
    counter = collections.Counter(entry['method'] for entry in entries.values())
    clash = sorted(name for name, count in counter.items() if count > 1)
    if clash:
        raise Error('method names reused across operations: %s' % ', '.join(clash))
    for key, entry in entries.items():
        for required in ('method', 'group', 'doc'):
            if not entry.get(required):
                raise Error('%s: %s is required' % (key, required))
        if not IDENT_RE.match(entry['method']):
            raise Error('%s: bad method name %r' % (key, entry['method']))
        if entry['group'] not in groups:
            raise Error('%s: unknown group %r' % (key, entry['group']))
    order = sorted(entries, key=lambda k: (list(groups).index(entries[k]['group']),
                                           known[k]['path'], known[k]['method']))
    return [Operation(key, known[key], entries[key], groups[entries[key]['group']]) for key in order]


def shape_operation(op, registry, dtos):
    op.args = [('String', java_field(name)) for name in op.path_names]
    shape_request(op, registry, dtos)
    shape_response(op, registry, dtos)


def shape_request(op, registry, dtos):
    fields = parse_fields(op.request_fields)
    named = op.entry.get('request')
    sends_body = op.http_method in BODY_METHODS
    if named:
        java = registry.java_name_of(named)
        target = registry.classes.get(java)
        if target is not None and target.pkg == MODEL_PKG:
            if fields and signature_of(fields) != signature_of(target.fields):
                raise Error('%s documents %s which do not match the model %s'
                            % (op.key, [w for w, _ in fields], java))
            op.args.append((java, decapitalize(java)))
            op.request_class = target
            op.body_var = decapitalize(java)
            return
        klass = dtos.get(REQUEST_PKG, java, op, fields,
                         'Request body of %s.' % _operation_doc_label(op))
        op.args.append((java, 'request'))
        op.request_class = klass
        op.body_var = 'request'
        return
    if not fields:
        return
    scalars = [(wire, parsed) for wire, parsed in fields
               if parsed.get('kind') == 'scalar' and parsed['java'] in SCALAR_TYPES]
    if len(scalars) != len(fields):
        raise Error('%s: parameters %s are not all scalar, name a request or query class'
                    % (op.key, [w for w, _ in fields if (w, ) not in [(s[0], ) for s in scalars]]))
    if not sends_body:
        for wire, parsed in scalars:
            op.args.append((parsed['java'], java_field(wire)))
            op.queries.append((wire, java_field(wire)))
        op.body_var = 'null'
        return
    if len(scalars) > MAX_FLATTENED_BODY_FIELDS:
        raise Error('%s: %d body fields are too many to flatten, name a request class'
                    % (op.key, len(scalars)))
    java = op.name[:1].upper() + op.name[1:] + 'Request'
    klass = dtos.get(REQUEST_PKG, java, op, scalars,
                     'Request body of %s.' % _operation_doc_label(op))
    op.request_class = klass
    var = 'request'
    op.body_var = var
    op.body_locals = ['        %s %s = new %s();' % (java, var, java)]
    for wire, parsed in scalars:
        op.args.append((parsed['java'], java_field(wire)))
        op.body_locals.append('        %s.%s = %s;' % (var, java_field(wire), java_field(wire)))


def _operation_doc_label(op):
    return '%s %s' % (op.http_method, op.path)


def shape_response(op, registry, dtos):
    named = op.entry.get('response')
    if not named or named == 'void':
        if op.entry.get('responseFields'):
            raise Error('%s: responseFields curated but the response is void' % op.key)
        return
    if '.' in named:
        op.returns = op.response_generic = named
        op.response_literal = named + '.class'
        return
    if named.startswith('[]'):
        inner = registry.java_name_of(named[2:])
        if inner not in registry.classes:
            raise Error('%s: unknown response element %s' % (op.key, named))
        op.returns = op.response_generic = 'List<%s>' % inner
        op.response_literal = 'Endpoint.listOf(%s.class)' % inner
        op.response_class = registry.classes[inner]
        return
    java = registry.java_name_of(named)
    fields = parse_fields(op.response_fields)
    existing = registry.classes.get(java)
    if existing is not None and existing.pkg == MODEL_PKG:
        if fields and signature_of(fields) != signature_of(existing.fields):
            raise Error('%s: response %s is a shared model but documents %s instead of %s'
                        % (op.key, java, [w for w, _ in fields], [w for w, _ in existing.fields]))
        op.returns = op.response_generic = java
        op.response_literal = '%s.class' % java
        op.response_class = existing
        return
    if existing is not None:
        raise Error('%s: response %s resolves to %s, which is not a model'
                    % (op.key, java, existing.fqn))
    if not fields:
        raise Error('%s: response %s is not a documented type and no responseFields were curated'
                    % (op.key, named))
    klass = dtos.get(MODEL_PKG, java, op, fields,
                     '%s: response of %s.' % (pretty(java), _operation_doc_label(op)))
    op.returns = op.response_generic = java
    op.response_literal = '%s.class' % java
    op.response_class = klass


