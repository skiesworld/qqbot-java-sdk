def segments(path):
    return [s for s in path.split('/') if s]


def shape_matches(template, concrete):
    return (len(template) == len(concrete)
            and all(part.startswith('{') and part.endswith('}') or part == other
                    for part, other in zip(template, concrete)))


def hygiene(spec):
    """Split the crawled endpoints into templated operations and their repeated example paths."""
    endpoints = spec['endpoints']
    templates = [(e['method'], segments(e['path'])) for e in endpoints if '{' in e['path']]
    keep, dropped = [], []
    for endpoint in endpoints:
        concrete = segments(endpoint['path'])
        if '{' not in endpoint['path'] and any(m == endpoint['method'] and shape_matches(t, concrete)
                                               for m, t in templates):
            dropped.append(endpoint)
        else:
            keep.append(endpoint)
    order = lambda e: (e['path'], e['method'])
    return sorted(keep, key=order), sorted(dropped, key=order)


def path_params(endpoint):
    return PATH_ARG_RE.findall(endpoint['path'])


def usable_field(field):
    name = (field.get('name') or '').strip()
    if not LOWER_IDENT_RE.match(name) or name in META_INFO_KEYS:
        return False
    return parse_type(field.get('type')).get('kind') != 'file'


def info_fields(endpoint):
    """The server-inter pages keep their parameter table in `info`, not in body/queryParams."""
    out = []
    for name, value in (endpoint.get('info') or {}).items():
        if not LOWER_IDENT_RE.match(name) or not isinstance(value, str) or '\t' not in value:
            continue
        head, _, tail = value.partition('\t')
        out.append({'name': name, 'type': head.strip(), 'required': False, 'desc': tail.strip()})
    return out


def dedupe(fields, taken=()):
    out, seen = [], set(taken)
    for field in fields:
        name = field['name'].strip()
        if name in seen or not usable_field(field):
            continue
        seen.add(name)
        out.append(field)
    return out


def request_fields_of(endpoint, entry):
    if entry.get('noRequestFields'):
        # the page's parameter table documents a response object, not the call
        return []
    override = entry.get('requestFields')
    if override:
        return dedupe([dict(f) for f in override])
    raw = dedupe(list(endpoint.get('body') or []) + list(endpoint.get('queryParams') or []))
    if not raw:
        raw = dedupe(info_fields(endpoint))
    return [f for f in raw if f['name'].strip() not in set(path_params(endpoint))]


def response_fields_of(endpoint, entry):
    override = entry.get('responseFields')
    if override:
        return dedupe([dict(f) for f in override])
    return dedupe(list(endpoint.get('response') or []))


def parse_fields(fields):
    return [(f['name'].strip(), parse_type(f.get('type'))) for f in fields]


def signature_of(fields):
    return [(wire, parsed.get('kind'), parsed.get('java'), parsed.get('name'))
            for wire, parsed in fields]


