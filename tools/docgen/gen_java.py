REGISTRY = None


def main():
    global REGISTRY
    with open(SPEC_PATH, encoding='utf-8') as handle:
        spec = json.load(handle)
    with open(NAMING_PATH, encoding='utf-8') as handle:
        naming = json.load(handle)

    keep, dropped = hygiene(spec)
    print('spec endpoints        : %d' % len(spec['endpoints']))
    print('retained operations   : %d' % len(keep))
    for endpoint in keep:
        print('  KEEP  %-6s %s' % (endpoint['method'], endpoint['path']))
    print('dropped example paths : %d' % len(dropped))
    for endpoint in dropped:
        print('  DROP  %-6s %s' % (endpoint['method'], endpoint['path']))

    if set(naming['apiGroups']) != set(API_ACCESSORS) or set(naming['apiGroups']) != set(API_DOCS):
        raise Error('naming.json apiGroups must be exactly %s' % ', '.join(sorted(API_ACCESSORS)))
    registry = Registry(naming)
    REGISTRY = registry
    constants = build_constants(naming, spec, registry)
    build_shared_models(spec, naming, registry)
    events = build_events(spec, registry)
    roles = build_event_roles(naming, events)
    operations = build_operations(spec, naming, keep)
    dtos = DtoIndex(registry)
    for op in operations:
        shape_operation(op, registry, dtos)
    for klass in list(registry.classes.values()):
        klass.resolve(registry)
    if registry.unresolved:
        detail = ', '.join('%s (%s)' % pair for pair in sorted(registry.unresolved.items()))
        raise Error('unresolved doc type refs: %s' % detail)
    if registry.untyped:
        raise Error('the docs leave the element type of these arrays empty, curate them in '
                    'naming.json: %s'
                    % ', '.join('%s x%d' % pair for pair in sorted(registry.untyped.items())))

    packages = [MODEL_PKG, REQUEST_PKG, CONSTANT_PKG, EVENT_PKG, API_PKG, ENDPOINT_PKG]
    clean_generated_packages(packages)
    written = 0
    for java, doc, values in constants:
        emit_constant(java, doc, values)
        written += 1
    buckets = collections.OrderedDict((pkg, []) for pkg in packages)
    for klass in registry.classes.values():
        emit_model(klass)
        buckets[klass.pkg].append(klass)
        written += 1
    for group, java_name in naming['apiGroups'].items():
        emit_api(java_name, API_DOCS[group], [op for op in operations if op.group == group])
        written += 1
    emit_endpoints(operations)
    written += 1
    emit_facade(naming['apiGroups'])
    written += 1
    emit_event_roles(roles)
    written += 1

    counts = collections.Counter(op.group for op in operations)
    shared = [k for k in buckets[MODEL_PKG] if not k.generated]
    responses = [k for k in buckets[MODEL_PKG] if k.generated]
    print('')
    print('java files written    : %d' % written)
    print('  shared models       : %d' % len(shared))
    print('  response types      : %d' % len(responses))
    print('  request types       : %d' % len(buckets[REQUEST_PKG]))
    print('  constant holders    : %d  %s'
          % (len(constants), ' '.join(java for java, _, _ in constants)))
    print('  event payloads      : %d  %s'
          % (len(buckets[EVENT_PKG]), ' '.join(k.java for k in buckets[EVENT_PKG])))
    print('  routing rows        : %d  %s'
          % (len(roles), ' '.join('%s=%s' % (env, sum(1 for r in roles if r.envelope == env))
                                  for env in ENVELOPES)))
    print('  api classes         : %d  %s' % (len(naming['apiGroups']) + 2,
                                              'Api Endpoints ' + ' '.join(naming['apiGroups'].values())))
    print('  operations          : %d' % len(operations))
    for group, java_name in sorted(naming['apiGroups'].items(), key=lambda kv: kv[1]):
        print('    %-24s %2d' % (java_name, counts[group]))


if __name__ == '__main__':
    try:
        main()
    except Error as error:
        sys.stderr.write('gen_java: %s\n' % str(error))
        sys.exit(1)
