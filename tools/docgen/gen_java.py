def _cased_segment(segment):
    """Mirror of Strings.casedSegment: shouty segments keep the capitals after a digit."""
    stripped = segment.replace('$', '')
    letters = [c for c in stripped if c.isalpha()]
    shouty = len(letters) > 1 and all(c.isupper() for c in letters)
    out, previous = [], ''
    for index, char in enumerate(stripped):
        if not char.isalpha():
            out.append(char)
            previous = char
            continue
        if index == 0:
            out.append(char.upper())
        elif shouty and previous.isdigit():
            out.append(char)
        else:
            out.append(char.lower())
        previous = char
    return ''.join(out)


def upper_camel(snake):
    """Port of io.github.skiesworld.qqbot.util.Strings.snakeToUpperCamel, which EventModels resolves with."""
    return ''.join(_cased_segment(s) for s in re.split(r'[_\- ]', snake) if s)


def lower_camel(snake):
    name = upper_camel(snake)
    return (name[:1].lower() + name[1:]) if name else name


def words(camel):
    """Split a java name into words, keeping acronym runs such as C2C in one piece."""
    out, current = [], ''
    for index, char in enumerate(camel):
        if char.isupper() and current:
            previous = current[-1]
            boundary = previous.islower()
            if previous.isupper() and index + 1 < len(camel) and camel[index + 1].islower():
                boundary = True
            if boundary:
                out.append(current)
                current = char
                continue
        current += char
    if current:
        out.append(current)
    return out


def const_name(method):
    return '_'.join(words(method)).upper()


def java_field(wire):
    """lowerCamel of the wire name; java keywords gain a Value suffix, the wire name never moves."""
    name = lower_camel(wire)
    return name + 'Value' if name in JAVA_KEYWORDS else name


def decapitalize(name):
    """lowerCamel of a java type name: only the leading acronym letters move."""
    index = 0
    while index < len(name) and name[index].isupper():
        index += 1
    if index == 0:
        return name
    if index == 1 or index == len(name):
        return name[:1].lower() + name[1:]
    return name[:index - 1].lower() + name[index - 1:]


def pretty(java_name):
    return ' '.join(words(java_name))


