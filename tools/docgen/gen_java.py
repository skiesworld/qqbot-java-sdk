def build_constants(naming, spec, registry):
    out = []
    for doc_name, cfg in sorted(naming.get('constants', {}).items()):
        java = cfg['java']
        values = collections.OrderedDict(cfg.get('values') or {})
        if not values:
            for field in spec['types'].get(doc_name, []):
                name = field['name'].strip()
                if not UPPER_RE.match(name):
                    continue
                number = re.match(r'^(0[xX][0-9a-fA-F]+|\d+)', field['type'].strip())
                if not number:
                    continue
                values[name] = int(number.group(1), 0)
            if not values:
                raise Error('constant %s has neither curated values nor parsable rows' % doc_name)
        doc = cfg.get('doc', 'Values of the %s table in the official API v2 docs.' % doc_name)
        out.append((java, doc, values))
        registry.constant_refs[doc_name] = java
    return out


def build_shared_models(spec, naming, registry):
    skip = set(naming.get('skipTypes', []))
    overrides = naming.get('typeFieldOverrides', {})
    constants = set(naming.get('constants', {}))

    def fields_for(doc_name, raw_fields):
        fields = [dict(f) for f in raw_fields]
        for name, java_type in sorted(overrides.get(doc_name, {}).items()):
            matched = False
            for field in fields:
                if field['name'].strip() == name:
                    field['type'] = java_type
                    matched = True
            if not matched:
                raise Error('typeFieldOverrides: %s documents no field %s' % (doc_name, name))
        return parse_fields(dedupe(fields))

    def register(doc_name, fields, doc):
        if doc_name in skip or doc_name in constants or not IDENT_RE.match(doc_name):
            return
        java = registry.java_name_of(doc_name)
        existing = registry.classes.get(java)
        if existing is not None:
            if not existing.fields and fields:
                existing.fields = fields
            return
        registry.add(Klass(java, MODEL_PKG, doc_name, doc)).fields = fields

    for doc_name in sorted(spec['types']):
        register(doc_name, fields_for(doc_name, spec['types'][doc_name]),
                 'Shared %s object from the official API v2 docs.' % doc_name)
    for source in list(spec['endpoints']) + list(spec['events']):
        for doc_name, raw in (source.get('types') or {}).items():
            register(doc_name, fields_for(doc_name, raw),
                     'Shared %s object from the official API v2 docs.' % doc_name)
    for klass in registry.classes.values():
        if not klass.fields:
            raise Error('model %s (%s) documents no usable field' % (klass.java, klass.wire))


def build_events(spec, registry):
    out = []
    for event in spec['events']:
        name = (event.get('info') or {}).get(u'\u4e8b\u4ef6\u540d')
        if not name:
            raise Error('an event page documents no event name (%s)' % event['file'])
        java = upper_camel(name)
        intent = (event.get('info') or {}).get('Intent') or ''
        doc = u'%s, the payload of the %s event (intent {@code %s}).' % (java, name, intent)
        klass = registry.add(Klass(java, EVENT_PKG, name, doc))
        klass.fields = parse_fields(dedupe(event.get('body') or []))
        out.append(klass)
    return out


def role_keys(entry, role):
    raw = entry.get(role) or []
    if isinstance(raw, str):
        raw = [raw]
    for key in raw:
        if not LOWER_IDENT_RE.match(key):
            raise Error('eventRoles %s: %s must name one payload key, got %r' % (entry.get('_name'), role, key))
    return list(dict.fromkeys(raw))


def build_event_roles(naming, crawled):
    """naming.json's eventRoles, checked against the crawled event names.

    Every event the gateway can push is listed here rather than derived: the envelope a dispatch is built into
    is what a handler's parameter type means, so it has be a decided fact, not a prefix match.
    """
    roles = naming.get('eventRoles')
    if not roles:
        raise Error('naming.json must curate eventRoles: the envelope of each event plus its actor/subject keys')
    rows = []
    for name, entry in roles.items():
        if name.startswith('_'):
            continue
        if not UPPER_RE.match(name):
            raise Error('eventRoles: %r is not an event name' % name)
        unknown = set(entry) - set(('envelope', 'actor', 'subject', 'doc'))
        if unknown:
            raise Error('eventRoles %s: unknown keys %s' % (name, ', '.join(sorted(unknown))))
        envelope = entry.get('envelope', 'PLAIN')
        if envelope not in ENVELOPES:
            raise Error('eventRoles %s: envelope must be one of %s, got %r'
                        % (name, ' '.join(ENVELOPES), envelope))
        entry = dict(entry, _name=name)
        rows.append(RoutingRow(name, envelope, role_keys(entry, 'actor'), role_keys(entry, 'subject'),
                               (entry.get('doc') or '').strip()))
    missing = sorted(k.wire for k in crawled if k.wire not in roles)
    if missing:
        raise Error('eventRoles has no row for the crawled events: %s' % ', '.join(missing))
    return rows


