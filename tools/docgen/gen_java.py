#!/usr/bin/env python3
"""Generate the SDK's data model and REST layer from spec.json + naming.json.

Reads the machine-extracted documentation dump (``spec.json``), applies endpoint hygiene (drops the
concrete example paths the docs repeat next to their templated form), looks every retained operation
up in the curated ``naming.json`` and writes Java 17 sources under ``src/main/java``:

  io.github.skiesworld.qqbot.model           shared payload types plus the response types of the operations
  io.github.skiesworld.qqbot.model.request   the request bodies of the operations
  io.github.skiesworld.qqbot.model.constant  int constant holders for the docs' value tables
  io.github.skiesworld.qqbot.event.model     the event payloads, named the way EventModels looks them up
  io.github.skiesworld.qqbot.api             one class per resource group, plus the Api facade
  io.github.skiesworld.qqbot.api.endpoint    Endpoints, one Endpoint constant per operation

Stdlib only, byte-for-byte reproducible, and it refuses to write anything when an operation has no
curated name. stdout stays ASCII because Windows consoles default to GBK; Chinese only ever reaches
UTF-8 files.

naming.json schema:

  apiGroups        group key -> generated class name; the accessors on Api follow API_ACCESSORS here
  typeAliases      doc type name -> java class name (Data -> UrlLinkData, DMS -> Dms, ...)
  skipTypes        registry entries that are not types at all (HTTP status tables, section rows, ...)
  scalarTypeNames  doc type tokens that are prose for a scalar ("ISO8601 timestamp" -> String)
  typeFieldOverrides  {type: {field: documented type}} fixes for tables the docs got wrong
  constants        value tables -> int constant holders; `values` curates the ones keyed by number
  endpoints        "METHOD /path-template" -> {title, group, method, doc, request, response,
                 requestFields?, responseFields?, noRequestFields?}
                 `request`/`response` name a generated DTO, an existing model, 'void' or a
                 fully qualified type; the *Fields keys replace what the crawler extracted, and
                 `noRequestFields` drops a table that documents a response rather than the call.

Usage: python tools/docgen/gen_java.py
"""

