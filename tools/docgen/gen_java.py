def parse_type(raw):
    """Read the free-form type column: ``[]UploadPart``, ``Channel 对象``, ``string 数组``, ``uint64``."""
    text = (raw or '').strip()
    if not text:
        return {'kind': 'object'}
    if text.startswith('[]'):
        return {'kind': 'array', 'item': parse_type(text[2:])}
    match = re.match(r'^(?:map|Map|object)\s*<\s*(\w+)\s*,\s*(.+)>$', text)
    if match:
        return {'kind': 'map', 'key': parse_type(match.group(1)), 'value': parse_type(match.group(2))}
    match = re.match(r'^(.*?)\[\]$', text)
    if match:
        return {'kind': 'array', 'item': parse_type(match.group(1))}
    if '数组' in text:
        return {'kind': 'array', 'item': parse_type(text.split('数组')[0])}
    text = re.sub(r'[（(].*?[）)]', ' ', text).strip()
    low = text.lower()
    if low in ('array', 'list'):
        return {'kind': 'array', 'item': {'kind': 'unknown'}}
    if low == 'file':
        return {'kind': 'file'}
    if low in SCALAR_KEYWORDS:
        return {'kind': 'scalar', 'java': SCALAR_KEYWORDS[low]}
    match = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)', text)
    if not match:
        return {'kind': 'scalar', 'java': 'String'}
    token = match.group(1)
    if token.lower() in SCALAR_KEYWORDS:
        return {'kind': 'scalar', 'java': SCALAR_KEYWORDS[token.lower()]}
    if token.lower() in ('array', 'list'):
        return {'kind': 'array', 'item': {'kind': 'unknown'}}
    return {'kind': 'ref', 'name': token}


class Klass(object):
    """One java class: the doc name it came from, its package and its (wire name, type) fields."""

    def __init__(self, java, pkg, wire, doc):
        self.java = java
        self.pkg = pkg
        self.wire = wire
        self.doc = doc
        self.generated = False
        self.fields = []     # [(wire name, parsed type)]
        self.members = []    # [(wire name, java name, java type)]

    @property
    def fqn(self):
        return '%s.%s' % (self.pkg, self.java)

    def resolve(self, registry):
        self.members = []
        seen = {}
        for wire, parsed in self.fields:
            name = java_field(wire)
            if name in seen:
                raise Error('%s: fields %s and %s both map to java field %s'
                            % (self.java, seen[name], wire, name))
            seen[name] = wire
            self.members.append((wire, name, registry.java_of(parsed, self)))


class Registry(object):
    """Every java class the generator may reference, plus doc type resolution."""

    def __init__(self, naming):
        self.alias = naming.get('typeAliases', {})
        self.scalar_names = naming.get('scalarTypeNames', {})
        self.classes = collections.OrderedDict()
        self.constant_refs = {}     # doc type name -> constant holder class
        self.unresolved = collections.OrderedDict()
        self.untyped = collections.OrderedDict()

    def add(self, klass):
        clash = self.classes.get(klass.java)
        if clash is not None and clash is not klass:
            raise Error('duplicate java class name %s (%s and %s)' % (klass.java, clash.fqn, klass.fqn))
        self.classes[klass.java] = klass
        return klass

    def java_name_of(self, doc_name):
        return self.alias.get(doc_name, doc_name)

    def ref_name(self, doc_name):
        """A doc type in a type column: a model class, a scalar, or nothing we can map."""
        name = self.java_name_of(doc_name)
        if name in self.constant_refs:
            return 'Long'
        if name in self.scalar_names:
            return self.scalar_names[name]
        return name if name in self.classes else None

    def java_of(self, parsed, owner):
        kind = parsed.get('kind')
        if kind == 'scalar':
            return parsed['java']
        if kind == 'map':
            return 'Map<String, %s>' % self.java_of(parsed['value'], owner)
        if kind == 'object':
            return 'Map<String, Object>'
        if kind == 'array':
            return 'List<%s>' % self.java_of(parsed['item'], owner)
        if kind == 'unknown':
            self.untyped[owner.java] = self.untyped.get(owner.java, 0) + 1
            return 'Map<String, Object>'
        if kind != 'ref':
            return 'String'
        name = self.ref_name(parsed['name'])
        if name in SCALAR_TYPES:
            return name
        if name is None:
            self.unresolved[parsed['name']] = owner.java
            return 'Map<String, Object>'
        return name


def imports_for(java_type, registry, owner=None):
    """Imports a declaration needs: every named type inside it that lives in another package."""
    out = set()
    for token in TOKEN_RE.findall(java_type):
        if token in JDK_TYPES:
            continue
        klass = registry.classes.get(token)
        if klass is not None:
            out.add(klass.fqn)
        elif '.' in token:
            out.add(token)
    if 'List<' in java_type:
        out.add('java.util.List')
    if 'Map<' in java_type:
        out.add('java.util.Map')
    if owner is not None:
        out.discard(owner.fqn)
    return {i for i in out if i}


